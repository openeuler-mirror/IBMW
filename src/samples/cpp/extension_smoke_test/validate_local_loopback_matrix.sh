strip_ansi() {
  sed 's/\x1b\[[0-9;]*m//g' "$1"
}

run_case() {
  local name="$1"
  local cfg="$2"
  local first_pattern="$3"
  local second_pattern="$4"
  local log_file="$TMP_DIR/ibmw_local_loopback_${name}.log"
  local clean_log="$TMP_DIR/ibmw_local_loopback_${name}.clean.log"
  local cfg_path="$CFG_DIR/$cfg"

  if [[ "$cfg" = /* ]]; then
    cfg_path="$cfg"
  fi

  if [ ! -f "$cfg_path" ]; then
    echo "ERROR: missing config for $name: $cfg_path" >&2
    exit 1
  fi

  echo "--- local-loopback: $name ($cfg) ---"
  set +e
  (
    cd "$BUILD_DIR" && timeout -s KILL "$RUN_TIMEOUT_SEC" "$IBMW_BIN" run "$cfg_path"
  ) >"$log_file" 2>&1
  local exit_code=$?
  set -e

  # These sample apps are long-running; timeout/SIGKILL is acceptable only when
  # the required functional markers are present in the captured log.
  if [[ "$exit_code" != 0 && "$exit_code" != 124 && "$exit_code" != 137 ]]; then
    echo "ERROR: $name exited before validation with code $exit_code" >&2
    echo "------- $name log -------" >&2
    strip_ansi "$log_file" >&2 || true
    exit "$exit_code"
  fi

  strip_ansi "$log_file" >"$clean_log"
  if ! grep -E "$first_pattern" "$clean_log" >/dev/null 2>&1; then
    echo "ERROR: $name missing first functional marker: $first_pattern" >&2
    echo "------- $name log -------" >&2
    cat "$clean_log" >&2
    exit 1
  fi
  if ! grep -E "$second_pattern" "$clean_log" >/dev/null 2>&1; then
    echo "ERROR: $name missing second functional marker: $second_pattern" >&2
    echo "------- $name log -------" >&2
    cat "$clean_log" >&2
    exit 1
  fi

  echo "PASS: $name"
}

run_expected_failure_case() {
  local name="$1"
  local cfg="$2"
  local expected_pattern="$3"
  local log_file="$TMP_DIR/ibmw_local_loopback_${name}.log"
  local clean_log="$TMP_DIR/ibmw_local_loopback_${name}.clean.log"
  local cfg_path="$CFG_DIR/$cfg"

  if [[ "$cfg" = /* ]]; then
    cfg_path="$cfg"
  fi

  if [ ! -f "$cfg_path" ]; then
    echo "ERROR: missing config for $name: $cfg_path" >&2
    exit 1
  fi

  echo "--- local-loopback: $name expected-fail ($cfg) ---"
  set +e
  (
    cd "$BUILD_DIR" && timeout -s KILL "$RUN_TIMEOUT_SEC" "$IBMW_BIN" run "$cfg_path"
  ) >"$log_file" 2>&1
  local exit_code=$?
  set -e

  strip_ansi "$log_file" >"$clean_log"
  if [[ "$exit_code" == 0 || "$exit_code" == 124 || "$exit_code" == 137 ]]; then
    echo "ERROR: $name unexpectedly ran like a long-lived valid sample, code $exit_code" >&2
    echo "------- $name log -------" >&2
    cat "$clean_log" >&2
    exit 1
  fi
  if ! grep -E "$expected_pattern" "$clean_log" >/dev/null 2>&1; then
    echo "ERROR: $name failed without expected marker: $expected_pattern" >&2
    echo "------- $name log -------" >&2
    cat "$clean_log" >&2
    exit 1
  fi

  echo "PASS: $name expected failure observed"
}


"""Generate TypeSupport/SchemaSupport entrypoints for module packages."""

from dataclasses import dataclass
import json

from ._common import _snake
from .custom_dds_types_gen import generate_custom_dds_schema


def _cpp_string(value: str) -> str:
    """Return a deterministic C++ string literal."""
    return json.dumps(value, ensure_ascii=True)


@dataclass(frozen=True)
class TypeSupportEntry:
    family: str
    cpp_type: str
    type_name: str
    includes: tuple[str, ...]
    schema_name: str = ""
    schema_expression: str = ""
    ros2_package: str = ""
    dds_target: str = ""
    custom_dds: bool = False


@dataclass(frozen=True)
class PackageTypeSupport:
    entries: tuple[TypeSupportEntry, ...]
    custom_dds_schema: str = ""

    def cmake_dependencies(self) -> tuple[str, ...]:
        deps = ["ibmw::api::type_support"]
        families = {entry.family for entry in self.entries}
        if "json" in families:
            deps.extend(("ibmw::api::cpp", "nlohmann_json::nlohmann_json"))
        if "dds" in families:
            deps.append("ibmw::api::dds_type_support")
        if any(entry.custom_dds for entry in self.entries):
            deps.append("fastcdr")
        if "ros2" in families:
            deps.append("ibmw::api::ros2_type_support")

        for entry in self.entries:
            if entry.dds_target:
                deps.append(entry.dds_target)
            if entry.ros2_package:
                package = entry.ros2_package
                deps.extend((
                    f"{package}::{package}__rosidl_generator_cpp",
                    f"{package}::{package}__rosidl_typesupport_introspection_cpp",
                ))

        return tuple(dict.fromkeys(deps))


def _is_ros2_message_module(module: dict) -> bool:
    if not module.get("message_type") or not module.get("ros2_msg_include"):
        return False
    return bool(
        module.get("transport") == "ros2"
        or module.get("_is_ros2_interop")
        or module.get("_is_loaned_publisher")
        or module.get("_is_loaned_subscriber")
        or module.get("_is_direct_iceoryx")
        or module.get("_is_direct_shm")
        or module.get("type") in {
            "direct_ros2_publisher",
            "direct_ros2_subscriber",
            "direct_iceoryx_publisher",
            "direct_iceoryx_subscriber",
            "direct_shm_publisher",
            "direct_shm_subscriber",
            "loaned_publisher",
            "loaned_subscriber",
        }
    )


def collect_package_type_support(
        project: dict, module_names: list[str]) -> PackageTypeSupport:
    """Collect the unique message types owned by one generated package."""
    module_map = project.get("_module_map") or {
        module["name"]: module for module in project.get("modules", [])
    }
    modules = [module_map[name] for name in module_names]
    entries: list[TypeSupportEntry] = []
    seen: set[tuple[str, str]] = set()

    def add(entry: TypeSupportEntry) -> None:
        key = (entry.family, entry.type_name)
        if key not in seen:
            seen.add(key)
            entries.append(entry)

    namespace = project["project"]["_namespace_cpp"]

    # Preserve the existing JSON contract: a package containing an owned JSON
    # module advertises every JSON type generated by the project.
    if any(
        module.get("transport") == "json"
        and not module.get("ros2_import_json_types_header")
        for module in modules
    ):
        for message in (project.get("json_types") or {}).get("messages", []):
            cpp_type = f"{namespace}::{message['name']}"
            add(TypeSupportEntry(
                family="json",
                cpp_type=cpp_type,
                type_name=f"json:{namespace}.{message['name']}",
                includes=("json_custom_types.h",),
            ))

    dds = project.get("dds_types") or {}
    dds_namespace = dds.get("_namespace_cpp", dds.get("namespace", ""))
    groups = {group["name"]: group for group in dds.get("groups", [])}
    msg_to_group = dds.get("_msg_to_group", {})
    custom_dds = project.get("custom_dds_types") or {}
    custom_namespace = custom_dds.get(
        "_namespace_cpp", custom_dds.get("namespace", namespace))
    custom_messages = custom_dds.get("_msg_map") or {
        message["name"]: message
        for message in custom_dds.get("messages", [])
    }

    for module in modules:
        if _is_ros2_message_module(module):
            cpp_type = module["message_type"]
            package = module.get("ros2_package") or cpp_type.split("::", 1)[0]
            add(TypeSupportEntry(
                family="ros2",
                cpp_type=cpp_type,
                type_name=f"ros2:{cpp_type.replace('::', '/')}",
                includes=(module["ros2_msg_include"],),
                ros2_package=package,
            ))
            continue

        if (module.get("transport") == "ros2"
                and module.get("type") in {"rpc_server", "rpc_client"}
                and module.get("ros2_service")):
            package = module["ros2_package"]
            service = module["ros2_service"]
            include = f"{package}/srv/{_snake(service)}.hpp"
            for suffix in ("Request", "Response"):
                cpp_type = f"{package}::srv::{service}_{suffix}"
                add(TypeSupportEntry(
                    family="ros2",
                    cpp_type=cpp_type,
                    type_name=f"ros2:{package}/srv/{service}_{suffix}",
                    includes=(include,),
                    ros2_package=package,
                ))
            continue

        if (module.get("transport") != "dds"
                or module.get("type") not in {"publisher", "subscriber"}):
            continue

        message_name = module.get("message_type", "")
        if message_name in custom_messages:
            message = custom_messages[message_name]
            cpp_type = f"{custom_namespace}::{message_name}"
            type_name = message.get("dds_type_name", cpp_type)
            header = message.get("header_filename", f"{_snake(message_name)}.h")
            add(TypeSupportEntry(
                family="dds",
                cpp_type=cpp_type,
                type_name=f"dds:{type_name}",
                includes=(f"protocol/{header}",),
                schema_name=cpp_type,
                schema_expression="kIbmwCustomDdsSchema",
                custom_dds=True,
            ))
            continue

        group_name = msg_to_group.get(message_name)
        group = groups.get(group_name or "")
        if not group:
            continue
        runtime_name = f"{namespace}::{message_name}"
        target = group.get("idl_gencode_target") or f"{_snake(group_name)}_idl_gencode"
        add(TypeSupportEntry(
            family="dds",
            cpp_type=f"{dds_namespace}::{message_name}",
            type_name=f"dds:{runtime_name}",
            includes=(
                f"{group_name}.hpp",
                f"{group_name}CdrAux.ipp",
                f"{group_name}Schema.hpp",
            ),
            schema_name=f"{dds_namespace}::{message_name}",
            schema_expression=f"ibmw::dds::schema::k{group_name}Idl",
            dds_target=target,
        ))

    custom_schema = ""
    if any(entry.custom_dds for entry in entries):
        custom_schema = generate_custom_dds_schema(project)
    return PackageTypeSupport(tuple(entries), custom_schema)


def generate_type_support_package_source(spec: PackageTypeSupport) -> str:
    if not spec.entries:
        raise ValueError("cannot generate an empty TypeSupport package")

    families = {entry.family for entry in spec.entries}
    includes = []
    for entry in spec.entries:
        includes.extend(entry.includes)
    includes = list(dict.fromkeys(includes))

    lines = [
        "// This file was generated by ibmw-gen. Do not edit.",
        "",
        '#include "type_support/type_support_pkg_main.h"',
    ]
    if "json" in families:
        lines.append('#include "cpp/util/json_type_support.h"')
    if "dds" in families:
        lines.append('#include "type_support/dds/dds_type_support.h"')
    if "ros2" in families:
        lines.extend((
            '#include "type_support/ros2/ros2_schema_support.h"',
            '#include "type_support/ros2/ros2_type_support_factory.h"',
        ))
    lines.append("")
    lines.extend(f'#include "{include}"' for include in includes)
    lines.extend(("", "namespace {", ""))

    if spec.custom_dds_schema:
        lines.append(
            f"constexpr char kIbmwCustomDdsSchema[] = "
            f"{_cpp_string(spec.custom_dds_schema)};")
        lines.append("")

    lines.append("const ibmw_type_support_base_t* type_support_array[]{")
    for entry in spec.entries:
        if entry.family == "json":
            expression = (
                f"ibmw::json::GetJsonMessageTypeSupport<{entry.cpp_type}>()")
        elif entry.family == "dds":
            expression = (
                "ibmw::dds::GetDdsMessageTypeSupportByName<"
                f"{entry.cpp_type}>({_cpp_string(entry.type_name[4:])})")
        else:
            expression = f"ibmw::GetRos2MessageTypeSupport<{entry.cpp_type}>()"
        lines.append(f"    {expression},")
    lines.extend(("};", "", "const ibmw_schema_support_base_t* schema_support_array[]{"))

    for entry in spec.entries:
        if entry.family == "json":
            expression = (
                f"ibmw::json::GetJsonMessageSchemaSupport<{entry.cpp_type}>()")
        elif entry.family == "dds":
            dds_name = entry.type_name[4:]
            schema_name = entry.schema_name or dds_name
            expression = (
                "ibmw::dds::GetDdsMessageSchemaSupport<"
                f"{entry.cpp_type}>({_cpp_string(schema_name)}, "
                f"{entry.schema_expression}, {_cpp_string(dds_name)})")
        else:
            expression = (
                f"ibmw::ros2::GetRos2MessageSchemaSupport<{entry.cpp_type}>()")
        lines.append(f"    {expression},")

    lines.extend((
        "};",
        "",
        "const ibmw_schema_support_package_v1_t schema_support_package{",
        "    .abi_version = IBMW_SCHEMA_SUPPORT_ABI_VERSION_V1,",
        "    .struct_size = sizeof(ibmw_schema_support_package_v1_t),",
        "    .entry_count = sizeof(schema_support_array) / sizeof(schema_support_array[0]),",
        "    .entries = schema_support_array,",
        "    .reserved = {},",
        "};",
        "",
        "const ibmw_type_support_package_v1_t type_support_package{",
        "    .abi_version = IBMW_TYPE_SUPPORT_PACKAGE_ABI_VERSION_V2,",
        "    .struct_size = sizeof(ibmw_type_support_package_v1_t),",
        "    .entry_count = sizeof(type_support_array) / sizeof(type_support_array[0]),",
        "    .entries = type_support_array,",
        "    .schema_support = &schema_support_package,",
        "    .reserved = {},",
        "};",
        "",
        "}  // namespace",
        "",
        'extern "C" {',
        "",
        "const ibmw_type_support_package_v1_t* IbmwDynlibGetTypeSupportPackageV1() {",
        "  return &type_support_package;",
        "}",
        "",
        '}  // extern "C"',
        "",
    ))
    return "\n".join(lines)


def generate_type_support_package_sources(project: dict) -> list[tuple[str, str]]:
    results = []
    for app in project.get("apps", []):
        spec = collect_package_type_support(project, app["modules"])
        if spec.entries:
            results.append((
                f"src/{app['_pkg_name']}/type_support_pkg_main.cc",
                generate_type_support_package_source(spec),
            ))
    return results

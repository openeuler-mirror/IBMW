# ── Plain type detection ─────────────────────────────────────────────────────

def is_plain_type(yaml_type: str, enum_names: set,
                  msg_plain_map: dict = None) -> bool:
    """Determine if a YAML field type is plain (trivially_copyable + standard_layout).

    A type is plain if it can be used for DDS zero-copy (data_sharing).
    - Primitives: plain
    - string, vector: NOT plain
    - array<T, N>: plain if T is plain
    - Enum classes: plain (fixed underlying type)
    - Nested messages: plain if the referenced message is plain
    """
    if yaml_type in PLAIN_PRIMITIVE_TYPES:
        return True
    if yaml_type in NON_PLAIN_TYPES:
        return False
    if yaml_type.startswith("vector<"):
        return False
    if yaml_type.startswith("array<"):
        inner = _parse_array_inner_type(yaml_type)
        if inner is None:
            return False
        return is_plain_type(inner, enum_names, msg_plain_map)
    if yaml_type in enum_names:
        return True
    # Check if it's a nested message type
    if msg_plain_map is not None and yaml_type in msg_plain_map:
        return msg_plain_map[yaml_type]
    return False


def is_message_plain(msg: dict, enum_names: set,
                     msg_plain_map: dict = None) -> bool:
    """A message is plain iff ALL its fields are plain."""
    return all(is_plain_type(f["type"], enum_names, msg_plain_map)
               for f in msg["fields"])


# ── Type resolution helpers ──────────────────────────────────────────────────

def _parse_array_inner_type(yaml_type: str) -> Optional[str]:
    """Parse 'array<T, N>' and return T."""
    if not yaml_type.startswith("array<") or not yaml_type.endswith(">"):
        return None
    inner = yaml_type[6:-1]  # strip "array<" and ">"
    # Find the last comma to split T and N
    last_comma = inner.rfind(",")
    if last_comma < 0:
        return None
    return inner[:last_comma].strip()


def _parse_array_size(yaml_type: str) -> Optional[str]:
    """Parse 'array<T, N>' and return N (as string, may be a constant name)."""
    if not yaml_type.startswith("array<") or not yaml_type.endswith(">"):
        return None
    inner = yaml_type[6:-1]
    last_comma = inner.rfind(",")
    if last_comma < 0:
        return None
    return inner[last_comma + 1:].strip()


def _parse_vector_inner_type(yaml_type: str) -> Optional[str]:
    """Parse 'vector<T>' and return T."""
    if not yaml_type.startswith("vector<") or not yaml_type.endswith(">"):
        return None
    return yaml_type[7:-1].strip()


def resolve_cpp_type(yaml_type: str, enum_names: set,
                     msg_names: set = None) -> str:
    """Convert a YAML type string to a C++ type string.

    Handles primitives, enums, nested message types, array<T, N>, vector<T>.
    """
    if yaml_type in YAML_TO_CPP:
        return YAML_TO_CPP[yaml_type]
    if yaml_type in enum_names:
        return yaml_type  # enum name used directly (in same namespace)
    if msg_names is not None and yaml_type in msg_names:
        return yaml_type  # nested message type (in same namespace)
    if yaml_type.startswith("array<"):
        inner_yaml = _parse_array_inner_type(yaml_type)
        size_str = _parse_array_size(yaml_type)
        if inner_yaml is None or size_str is None:
            raise ValueError(f"Invalid array type syntax: '{yaml_type}'")
        inner_cpp = resolve_cpp_type(inner_yaml, enum_names, msg_names)
        return f"std::array<{inner_cpp}, {size_str}>"
    if yaml_type.startswith("vector<"):
        inner_yaml = _parse_vector_inner_type(yaml_type)
        if inner_yaml is None:
            raise ValueError(f"Invalid vector type syntax: '{yaml_type}'")
        inner_cpp = resolve_cpp_type(inner_yaml, enum_names, msg_names)
        return f"std::vector<{inner_cpp}>"
    raise ValueError(f"Unknown YAML type: '{yaml_type}'")


def _is_enum_field(yaml_type: str, enum_names: set) -> bool:
    """Check if a field type is an enum."""
    return yaml_type in enum_names


def _is_nested_msg_field(yaml_type: str, msg_names: set) -> bool:
    """Check if a field type is a nested message (direct, array, or vector)."""
    if msg_names is None:
        return False
    if yaml_type in msg_names:
        return True
    if yaml_type.startswith("array<"):
        inner = _parse_array_inner_type(yaml_type)
        return inner is not None and inner in msg_names
    if yaml_type.startswith("vector<"):
        inner = _parse_vector_inner_type(yaml_type)
        return inner is not None and inner in msg_names
    return False


def _enum_underlying_cpp(enum_def: dict) -> str:
    """Get the C++ underlying type for an enum."""
    ut = enum_def.get("underlying_type", "uint32")
    return ENUM_UNDERLYING_CPP.get(ut, "uint32_t")


# ── Include detection ────────────────────────────────────────────────────────

def _required_includes(msg: dict, enum_names: set,
                       msg_names: set = None) -> list:
    """Determine required C++ includes for a message type.

    Returns sorted list of include strings like "<string>", "<array>", etc.
    Does NOT include nested message headers — those are returned separately.
    """
    includes = {"<cstdint>"}  # always needed for int types
    for f in msg["fields"]:
        t = f["type"]
        if t == "string":
            includes.add("<string>")
        elif t.startswith("array<"):
            includes.add("<array>")
            inner = _parse_array_inner_type(t)
            if inner == "string":
                includes.add("<string>")
            elif inner is not None and inner.startswith("vector<"):
                includes.add("<vector>")
        elif t.startswith("vector<"):
            includes.add("<vector>")
            inner = _parse_vector_inner_type(t)
            if inner == "string":
                includes.add("<string>")
    return sorted(includes)


def _nested_msg_includes(msg: dict, msg_names: set) -> list:
    """Determine #include directives for nested message types.

    Returns sorted list of include strings like '"protocol/header.h"'.
    """
    if not msg_names:
        return []
    refs = set()
    for f in msg["fields"]:
        t = f["type"]
        if t in msg_names:
            refs.add(t)
        elif t.startswith("array<"):
            inner = _parse_array_inner_type(t)
            if inner in msg_names:
                refs.add(inner)
        elif t.startswith("vector<"):
            inner = _parse_vector_inner_type(t)
            if inner in msg_names:
                refs.add(inner)
    return sorted(f'"protocol/{_to_snake_case(r)}.h"' for r in refs)


# ── Code generation: enums ───────────────────────────────────────────────────

def _gen_enum_block(enum_def: dict) -> str:
    """Generate a single enum class definition."""
    name = enum_def["name"]
    underlying = _enum_underlying_cpp(enum_def)
    values = enum_def["values"]

    lines = [f"enum class {name} : {underlying} {{"]
    for i, v in enumerate(values):
        comma = "," if i < len(values) - 1 else ""
        comment = f"  // {v['comment']}" if v.get("comment") else ""
        lines.append(f"  {v['name']} = {v['value']}{comma}{comment}")
    lines.append("};")
    return "\n".join(lines)


# ── Code generation: constants ───────────────────────────────────────────────

def _gen_constant(const_def: dict) -> str:
    """Generate a single static constexpr constant."""
    name = const_def["name"]
    cpp_type = YAML_TO_CPP.get(const_def["type"], const_def["type"])
    value = const_def["value"]
    return f"static constexpr {cpp_type} {name} = {value};"


# ── Code generation: struct ──────────────────────────────────────────────────

def _gen_struct(msg: dict, enum_names: set, ns_cpp: str,
                msg_names: set = None, msg_plain_map: dict = None) -> str:
    """Generate the struct definition with fields, constructors, and
    serialize/deserialize member functions."""
    name = msg["name"]
    fields = msg["fields"]
    is_plain = msg.get("_is_plain", False)
    has_ctor = msg.get("constructor_args", False)

    lines = [f"struct {name} {{"]
    # Plain type marker
    plain_str = "true" if is_plain else "false"
    not_plain_reason = ""
    if not is_plain:
        non_plain_fields = [f["name"] for f in fields
                           if not is_plain_type(f["type"], enum_names,
                                                msg_plain_map)]
        if non_plain_fields:
            not_plain_reason = f"  // contains non-plain field(s): {', '.join(non_plain_fields)}"
    lines.append(f"  static constexpr bool kIsPlainType = {plain_str};{not_plain_reason}")
    lines.append("")

    # Fields
    for f in fields:
        cpp_type = resolve_cpp_type(f["type"], enum_names, msg_names)
        default = f.get("default", "")
        if default:
            # For array/vector/nested-msg types, don't use default (they have value-init)
            if (f["type"].startswith("array<") or f["type"].startswith("vector<")
                    or (msg_names and f["type"] in msg_names)):
                lines.append(f"  {cpp_type} {f['name']}{{}};")
            else:
                lines.append(f"  {cpp_type} {f['name']} = {default};")
        else:
            # No default specified
            if f["type"] in PLAIN_PRIMITIVE_TYPES:
                # Zero-initialize primitives
                lines.append(f"  {cpp_type} {f['name']} = {PRIMITIVE_DEFAULTS.get(f['type'], '0')};")
            elif f["type"] in enum_names:
                # Enum: no default specified, use first value or zero
                lines.append(f"  {cpp_type} {f['name']}{{}};")
            else:
                # string, array, vector, nested msg: default construction
                lines.append(f"  {cpp_type} {f['name']}{{}};")

    lines.append("")

    # Default constructor
    lines.append(f"  {name}() = default;")

    # Non-default constructor
    if has_ctor:
        lines.append(_gen_constructor(name, fields, enum_names, msg_names))

    lines.append("")

    # serialize member
    lines.append("  void serialize(eprosima::fastcdr::Cdr& cdr) const {")
    ser_parts = []
    for f in fields:
        if _is_enum_field(f["type"], enum_names):
            # Cast enum to underlying type
            underlying = "uint32_t"  # default; could look up actual
            ser_parts.append(f"static_cast<{underlying}>({f['name']})")
        else:
            ser_parts.append(f"{f['name']}")
    lines.append(f"    cdr << {' << '.join(ser_parts)};")
    lines.append("  }")

    lines.append("")

    # deserialize member
    lines.append("  void deserialize(eprosima::fastcdr::Cdr& cdr) {")
    # Group consecutive non-enum fields for compact >> chains
    buf = []
    for f in fields:
        if _is_enum_field(f["type"], enum_names):
            # Flush non-enum buffer first
            if buf:
                lines.append(f"    cdr >> {' >> '.join(buf)};")
                buf = []
            # Enum: read via temp
            underlying = "uint32_t"
            lines.append(f"    {underlying} {f['name']}_val;")
            lines.append(f"    cdr >> {f['name']}_val;")
            lines.append(f"    {f['name']} = static_cast<{f['type']}>({f['name']}_val);")
        else:
            buf.append(f"{f['name']}")
    if buf:
        lines.append(f"    cdr >> {' >> '.join(buf)};")
    lines.append("  }")

    lines.append("};")
    return "\n".join(lines)


def _gen_constructor(name: str, fields: list, enum_names: set,
                     msg_names: set = None) -> str:
    """Generate a non-default constructor with all fields as parameters."""
    params = []
    inits = []
    for f in fields:
        cpp_type = resolve_cpp_type(f["type"], enum_names, msg_names)
        param_name = f"{f['name']}_"
        # Use move semantics for string, vector, array, and nested message types
        is_nested = msg_names and f["type"] in msg_names
        if (f["type"] == "string" or f["type"].startswith("vector<")
                or f["type"].startswith("array<") or is_nested):
            params.append(f"{cpp_type} {param_name}")
            inits.append(f"{f['name']}(std::move({param_name}))")
        else:
            params.append(f"{cpp_type} {param_name}")
            inits.append(f"{f['name']}({param_name})")

    param_str = ", ".join(params)
    init_str = ", ".join(inits)

    lines = [f"  {name}({param_str})"]
    lines.append(f"      : {init_str} {{}}")
    return "\n".join(lines)


# ── Code generation: eprosima specializations ────────────────────────────────

def _gen_calculate_serialized_size(msg: dict, enum_names: set,
                                    fq_name: str) -> str:
    """Generate calculate_serialized_size template specialization."""
    fields = msg["fields"]
    lines = [
        "template <>",
        "inline size_t calculate_serialized_size(",
        "    CdrSizeCalculator& calculator,",
        f"    const {fq_name}& data,",
        "    size_t& current_alignment) {",
        "  size_t total = 0;",
    ]
    for i, f in enumerate(fields):
        if _is_enum_field(f["type"], enum_names):
            lines.append(f"  total += calculator.calculate_member_serialized_size(")
            lines.append(f"      MemberId({i}), static_cast<uint32_t>(data.{f['name']}), current_alignment);")
        else:
            lines.append(f"  total += calculator.calculate_member_serialized_size(")
            lines.append(f"      MemberId({i}), data.{f['name']}, current_alignment);")
    lines.append("  return total;")
    lines.append("}")
    return "\n".join(lines)


def _gen_serialize_free(msg: dict, enum_names: set, fq_name: str) -> str:
    """Generate serialize<T> template specialization."""
    fields = msg["fields"]
    lines = [
        "template <>",
        "inline void serialize(",
        "    Cdr& scdr,",
        f"    const {fq_name}& data) {{",
    ]
    parts = []
    for f in fields:
        if _is_enum_field(f["type"], enum_names):
            parts.append(f"static_cast<uint32_t>(data.{f['name']})")
        else:
            parts.append(f"data.{f['name']}")

    # Format as multi-line << chain
    if len(parts) <= 3:
        lines.append(f"  scdr << {' << '.join(parts)};")
    else:
        lines.append(f"  scdr << {parts[0]}")
        for p in parts[1:-1]:
            lines.append(f"       << {p}")
        lines.append(f"       << {parts[-1]};")
    lines.append("}")
    return "\n".join(lines)


def _gen_deserialize_free(msg: dict, enum_names: set,
                           fq_name: str, ns_cpp: str) -> str:
    """Generate deserialize<T> template specialization."""
    fields = msg["fields"]
    lines = [
        "template <>",
        "inline void deserialize(",
        "    Cdr& cdr,",
        f"    {fq_name}& data) {{",
    ]

    # Group consecutive non-enum fields
    buf = []
    for f in fields:
        if _is_enum_field(f["type"], enum_names):
            # Flush buffer
            if buf:
                lines.append(f"  cdr >> {' >> '.join(buf)};")
                buf = []
            # Enum deserialization
            lines.append(f"  uint32_t {f['name']}_val;")
            lines.append(f"  cdr >> {f['name']}_val;")
            # Use fully-qualified enum type in the free function
            lines.append(f"  data.{f['name']} = static_cast<{ns_cpp}::{f['type']}>({f['name']}_val);")
        else:
            buf.append(f"data.{f['name']}")
    if buf:
        if len(buf) <= 4:
            lines.append(f"  cdr >> {' >> '.join(buf)};")
        else:
            lines.append(f"  cdr >> {buf[0]}")
            for b in buf[1:-1]:
                lines.append(f"      >> {b}")
            lines.append(f"      >> {buf[-1]};")

    lines.append("}")
    return "\n".join(lines)


# ── Code generation: full header file ────────────────────────────────────────

def _gen_header_file(msg: dict, enums: list, constants: list,
                      ns_cpp: str, project: dict,
                      all_enum_names: set,
                      all_msg_names: set = None,
                      msg_plain_map: dict = None) -> str:
    """Assemble the complete header file for one message type."""
    fq_name = f"{ns_cpp}::{msg['name']}"
    dds_type_name = msg.get("dds_type_name", fq_name)

    includes = _required_includes(msg, all_enum_names, all_msg_names)
    nested_includes = _nested_msg_includes(msg, all_msg_names or set())

    parts = []
    parts.append(_COPYRIGHT)
    parts.append("")
    parts.append("#pragma once")
    parts.append("")

    # Standard includes
    for inc in includes:
        parts.append(f"#include {inc}")
    parts.append("")
    parts.append("#include <fastcdr/Cdr.h>")
    parts.append("#include <fastcdr/FastBuffer.h>")
    parts.append("")
    parts.append("// v2-to-v1 compat: provides CdrSizeCalculator for size estimation")
    parts.append('#include "type_support/dds/fastcdr_v1_compat.h"')
    parts.append('#include "type_support/dds/dds_type_support.h"')

    # Nested message includes
    if nested_includes:
        parts.append("")
        parts.append("// Nested message types")
        for inc in nested_includes:
            parts.append(f"#include {inc}")

    parts.append("")

    # Open namespace
    parts.append(f"namespace {ns_cpp} {{")
    parts.append("")

    # Constants (only those referenced by this message's fields)
    msg_constants = _get_message_constants(msg, constants)
    for c in msg_constants:
        parts.append(_gen_constant(c))
    if msg_constants:
        parts.append("")

    # Enums referenced by this message
    msg_enums = _get_message_enums(msg, enums)
    for e in msg_enums:
        parts.append(_gen_enum_block(e))
        parts.append("")

    # Struct
    parts.append(_gen_struct(msg, all_enum_names, ns_cpp,
                             all_msg_names, msg_plain_map))
    parts.append("")

    # Close namespace
    parts.append(f"}}  // namespace {ns_cpp}")
    parts.append("")

    # IBMW_DDS_TYPE_NAME macro (must be outside namespace)
    parts.append(f'IBMW_DDS_TYPE_NAME({fq_name},')
    parts.append(f'                   "{dds_type_name}")')
    parts.append("")

    # FastCDR specializations
    parts.append("// FastCDR v1 serialize/deserialize specializations")
    parts.append("namespace eprosima {")
    parts.append("namespace fastcdr {")
    parts.append("")

    parts.append("// Size calculation")
    parts.append(_gen_calculate_serialized_size(msg, all_enum_names, fq_name))
    parts.append("")

    parts.append("// Serialize")
    parts.append(_gen_serialize_free(msg, all_enum_names, fq_name))
    parts.append("")

    parts.append("// Deserialize")
    parts.append(_gen_deserialize_free(msg, all_enum_names, fq_name, ns_cpp))
    parts.append("")

    parts.append("}  // namespace fastcdr")
    parts.append("}  // namespace eprosima")

    return "\n".join(parts) + "\n"


def _get_message_enums(msg: dict, enums: list) -> list:
    """Get enum definitions referenced by a message's fields."""
    enum_names_used = set()
    for f in msg["fields"]:
        t = f["type"]
        # Direct enum reference
        for e in enums:
            if t == e["name"]:
                enum_names_used.add(e["name"])
            # Also check inside array/vector
            if t.startswith("array<") or t.startswith("vector<"):
                inner = _parse_array_inner_type(t) or _parse_vector_inner_type(t)
                if inner == e["name"]:
                    enum_names_used.add(e["name"])
    return [e for e in enums if e["name"] in enum_names_used]


def _get_message_constants(msg: dict, constants: list) -> list:
    """Get constants referenced by a message's field types or defaults.

    A constant is 'referenced' if its name appears in an array size
    or in a field default value.
    """
    if not constants:
        return []
    const_names = {c["name"] for c in constants}
    used = set()
    for f in msg["fields"]:
        t = f["type"]
        # Check array size
        if t.startswith("array<"):
            size_str = _parse_array_size(t)
            if size_str in const_names:
                used.add(size_str)
        # Check default value
        default = f.get("default", "")
        if default:
            for cn in const_names:
                if cn in default:
                    used.add(cn)
    return [c for c in constants if c["name"] in used]


# ── Snake case helper ────────────────────────────────────────────────────────

def _to_snake_case(name: str) -> str:
    """Convert PascalCase to snake_case."""
    result = []
    for i, ch in enumerate(name):
        if ch.isupper() and i > 0:
            prev = name[i - 1]
            if prev.islower() or prev.isdigit():
                result.append("_")
            elif i + 1 < len(name) and name[i + 1].islower():
                result.append("_")
        result.append(ch.lower())
    return "".join(result)


# ── Public API ───────────────────────────────────────────────────────────────

def _topological_sort_messages(messages: list, all_msg_names: set) -> list:
    """Topologically sort messages so that dependencies come before dependents.

    Messages with no nested-message dependencies come first. If message B
    references message A as a field type, A appears before B in the output.

    The schema validator already rejects circular references, so this
    function assumes the dependency graph is a DAG.
    """
    if not all_msg_names:
        return messages

    # Build name -> msg lookup
    msg_by_name = {m["name"]: m for m in messages}

    # Build dependency graph: msg_name -> set of msg_names it depends on
    deps = {}
    for msg in messages:
        msg_deps = set()
        for f in msg["fields"]:
            t = f["type"]
            if t in all_msg_names and t != msg["name"]:
                msg_deps.add(t)
            elif t.startswith("array<"):
                inner = _parse_array_inner_type(t)
                if inner in all_msg_names:
                    msg_deps.add(inner)
            elif t.startswith("vector<"):
                inner = _parse_vector_inner_type(t)
                if inner in all_msg_names:
                    msg_deps.add(inner)
        deps[msg["name"]] = msg_deps

    # Kahn's algorithm
    in_degree = {name: 0 for name in msg_by_name}
    for name, d in deps.items():
        for dep in d:
            if dep in in_degree:
                in_degree[dep]  # ensure exists (it should)
    # Count incoming edges
    for name, d in deps.items():
        for dep in d:
            pass  # dep is depended upon by name — we want dep before name
    # Recompute: in_degree[X] = number of messages that X depends on? No.
    # We want: if A is depended on by B, A comes first.
    # So edge direction: B -> A (B depends on A).
    # in_degree[A] = number of msgs that must come AFTER A = not useful.
    # Let's think again: we want topological order where if B depends on A,
    # A appears before B. Standard topo sort: edge from A to B means A before B.
    # Our deps: B depends on A, meaning A must come before B.
    # So edge: A -> B in the standard sense.
    # Reverse: for each B, deps[B] = {A, ...} means edges A->B.
    # in_degree[B] += 1 for each A in deps[B].
    in_degree = {name: 0 for name in msg_by_name}
    for name, d in deps.items():
        in_degree[name] += len(d)

    from collections import deque
    queue = deque(name for name, deg in in_degree.items() if deg == 0)
    result = []
    while queue:
        node = queue.popleft()
        result.append(msg_by_name[node])
        # For all messages that depend on this node, reduce in-degree
        for name, d in deps.items():
            if node in d:
                in_degree[name] -= 1
                if in_degree[name] == 0:
                    queue.append(name)

    # If not all messages are in result, there's a cycle (should be caught by schema)
    if len(result) != len(messages):
        # Fallback: return original order
        return messages

    return result


def _resolve_idl_type(yaml_type: str, enum_names: set,
                      msg_names: set) -> str:
    if yaml_type in YAML_TO_IDL:
        return YAML_TO_IDL[yaml_type]
    if yaml_type in enum_names or yaml_type in msg_names:
        return yaml_type
    if yaml_type.startswith("vector<"):
        inner = _parse_vector_inner_type(yaml_type)
        return f"sequence<{_resolve_idl_type(inner, enum_names, msg_names)}>"
    if yaml_type.startswith("array<"):
        inner = _parse_array_inner_type(yaml_type)
        return _resolve_idl_type(inner, enum_names, msg_names)
    raise ValueError(f"Unknown custom DDS type: '{yaml_type}'")


def generate_custom_dds_schema(project: dict) -> str:
    """Generate canonical OMG IDL metadata for custom DDS C++ types."""
    cdt = project.get("custom_dds_types")
    if not cdt:
        return ""

    namespace = cdt.get(
        "_namespace_cpp",
        cdt.get("namespace", project["project"]["_namespace_cpp"]),
    )
    namespace_parts = [part for part in namespace.split("::") if part]
    enums = cdt.get("enums", [])
    messages = cdt.get("messages", [])
    enum_names = {enum["name"] for enum in enums}
    msg_names = {message["name"] for message in messages}
    messages = _topological_sort_messages(messages, msg_names)

    lines = ["// Generated by ibmw-gen from custom_dds_types."]
    for depth, part in enumerate(namespace_parts):
        lines.append(f"{'  ' * depth}module {part} {{")
    indent = "  " * len(namespace_parts)

    for constant in cdt.get("constants", []):
        idl_type = _resolve_idl_type(constant["type"], enum_names, msg_names)
        lines.append(
            f"{indent}const {idl_type} {constant['name']} = "
            f"{constant['value']};")

    for enum in enums:
        lines.append("")
        lines.append(f"{indent}enum {enum['name']} {{")
        values = enum["values"]
        for index, value in enumerate(values):
            comma = "," if index + 1 < len(values) else ""
            lines.append(
                f"{indent}  @value({value['value']}) {value['name']}{comma}")
        lines.append(f"{indent}}};")

    for message in messages:
        lines.append("")
        lines.append(f"{indent}struct {message['name']} {{")
        for field in message["fields"]:
            idl_type = _resolve_idl_type(field["type"], enum_names, msg_names)
            if field["type"].startswith("array<"):
                array_size = _parse_array_size(field["type"])
                lines.append(
                    f"{indent}  {idl_type} {field['name']}[{array_size}];")
            else:
                lines.append(f"{indent}  {idl_type} {field['name']};")
        lines.append(f"{indent}}};")

    for depth in range(len(namespace_parts) - 1, -1, -1):
        lines.append(f"{'  ' * depth}}};")
    lines.append("")
    return "\n".join(lines)


def generate_custom_dds_type_files(project: dict) -> list:
    """Generate custom DDS type headers as (rel_path, content) tuples.

    This follows the same pattern as other ibmw-gen generators, returning
    pairs of (relative_path, file_content) for the main entry point to write.

    Args:
        project: The enriched project data from schema.py.

    Returns:
        List of (rel_path, content) tuples.
    """
    cdt = project.get("custom_dds_types")
    if not cdt:
        return []

    ns_cpp = cdt.get("namespace", project["project"].get("_namespace_cpp",
                                                          project["project"]["namespace"]))
    enums = cdt.get("enums", [])
    constants = cdt.get("constants", [])
    messages = cdt.get("messages", [])
    all_enum_names = {e["name"] for e in enums}
    all_msg_names = {m["name"] for m in messages}

    # Topologically sort messages so dependencies are generated first
    messages = _topological_sort_messages(messages, all_msg_names)

    # Build msg_plain_map: compute is_plain in topological order so that
    # nested message plainness is resolved before it's needed.
    msg_plain_map = {}
    for msg in messages:
        plain = is_message_plain(msg, all_enum_names, msg_plain_map)
        msg["_is_plain"] = plain
        msg_plain_map[msg["name"]] = plain

    results = []
    for msg in messages:
        filename = msg.get("header_filename",
                           _to_snake_case(msg["name"]) + ".h")
        rel_path = os.path.join("protocol", filename)
        content = _gen_header_file(msg, enums, constants, ns_cpp, project,
                                    all_enum_names, all_msg_names,
                                    msg_plain_map)
        results.append((rel_path, content))

    return results


def generate(project: dict, out_dir: str) -> list:
    """Generate custom DDS type headers (writes files directly).

    Args:
        project: The enriched project data from schema.py.
        out_dir: Output directory root.

    Returns:
        List of generated file paths (relative to out_dir).
    """
    results = generate_custom_dds_type_files(project)
    if not results:
        return []

    generated_files = []
    for rel_path, content in results:
        filepath = output_file_path(out_dir, rel_path)
        os.makedirs(os.path.dirname(filepath), exist_ok=True)
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)
        generated_files.append(rel_path)
        print(f"  Generated: {rel_path}")

    return generated_files

# DDS type bridge header and CDR impl generator for ibmw-gen.

"""Generate src/*_dds_types.h and src/*_cdr_impl.cc files."""


def _snake_name(name: str) -> str:
    """Convert PascalCase to snake_case."""
    result = []
    for i, ch in enumerate(name):
        if ch.isupper() and i > 0:
            prev = name[i - 1]
            if prev.islower() or prev.isdigit():
                result.append("_")
            elif i + 1 < len(name) and name[i + 1].islower():
                result.append("_")
        result.append(ch.lower())
    return "".join(result)


def _resolve_imports_transitive(group_name: str, groups: list) -> list[str]:
    """Resolve transitive import chain for a group.

    Returns the list of group names in dependency order (deepest first),
    NOT including the group itself.
    """
    group_map = {g["name"]: g for g in groups}
    visited = set()
    order = []

    def dfs(name):
        if name in visited:
            return
        visited.add(name)
        g = group_map.get(name, {})
        for imp in g.get("imports", []):
            dfs(imp)
        order.append(name)

    g = group_map.get(group_name, {})
    for imp in g.get("imports", []):
        dfs(imp)

    return order


def generate_dds_type_bridges(project: dict) -> list[tuple[str, str]]:
    """Generate type bridge headers and CDR impl files.

    Returns list of (rel_path, content) tuples.
    """
    dds = project["dds_types"]
    ns_cpp = dds["_namespace_cpp"]
    groups = dds.get("groups", [])

    results = []

    for g in groups:
        group_name = g["name"]
        snake = _snake_name(group_name)
        messages = g.get("messages", [])
        is_external = g.get("_external", False)

        if not messages:
            continue

        # Check if this group is used only by RPC (not pub/sub).
        # RPC groups don't need a type bridge header — the RPC gencode header
        # handles everything.  Only pub/sub groups need the bridge.
        rpc_services = dds.get("rpc_services", [])
        is_rpc_group = any(svc["group"] == group_name for svc in rpc_services)

        # Generate type bridge header for pub/sub groups (both external and local)
        if not is_rpc_group:
            hdr_lines = []
            hdr_lines.append("// This file was generated by ibmw-gen. Do not edit.")
            hdr_lines.append("")
            hdr_lines.append("#pragma once")
            hdr_lines.append("")
            hdr_lines.append('#include "internal/typesupport/dds/dds_transport.h"')
            hdr_lines.append("")
            hdr_lines.append(f'#include "{group_name}.hpp"')
            hdr_lines.append(f'#include "{group_name}CdrAux.ipp"')
            hdr_lines.append("")

            for msg in messages:
                hdr_lines.append(
                    f'IBMW_DDS_TYPE_NAME({ns_cpp}::{msg["name"]},')
                hdr_lines.append(
                    f'                    "{project["project"]["_namespace_cpp"]}::{msg["name"]}")')
                hdr_lines.append("")

            results.append((f"src/{snake}_dds_types.h", "\n".join(hdr_lines)))

        # Skip CDR impl for external groups — the pre-built target provides it
        if is_external:
            continue

        # ── CDR impl file (local groups only) ──
        cdr_lines = []
        cdr_lines.append("// This file was generated by ibmw-gen. Do not edit.")

        # Include dependencies first (transitive)
        deps = _resolve_imports_transitive(group_name, groups)
        if deps:
            cdr_lines.append(f"// Dependencies: {', '.join(deps)}")

        for dep in deps:
            cdr_lines.append(f'#include "{dep}CdrAux.ipp"')

        cdr_lines.append(f'#include "{group_name}CdrAux.ipp"')
        cdr_lines.append("")

        results.append((f"src/{snake}_cdr_impl.cc", "\n".join(cdr_lines)))

    return results

# JSON types header generator for ibmw-gen.

"""Generate src/json_custom_types.h for generated JSON modules."""

import json
from textwrap import dedent

# Mapping from YAML type names to C++ type info
_CPP_TYPE_MAP = {
    "string": ("std::string", '""'),
    "bool": ("bool", "false"),
    "int8_t": ("int8_t", "0"),
    "int16_t": ("int16_t", "0"),
    "int32_t": ("int32_t", "0"),
    "int64_t": ("int64_t", "0"),
    "uint8_t": ("uint8_t", "0"),
    "uint16_t": ("uint16_t", "0"),
    "uint32_t": ("uint32_t", "0"),
    "uint64_t": ("uint64_t", "0"),
    "float": ("float", "0.0f"),
    "double": ("double", "0.0"),
}


def _resolve_cpp_type(yaml_type: str) -> tuple[str, str]:
    """Return (cpp_type, default_value) for a YAML type."""
    if yaml_type in _CPP_TYPE_MAP:
        return _CPP_TYPE_MAP[yaml_type]
    # vector<T>
    if yaml_type.startswith("vector<") and yaml_type.endswith(">"):
        inner = yaml_type[7:-1]
        inner_cpp, _ = _resolve_cpp_type(inner)
        return (f"std::vector<{inner_cpp}>", "{}")
    # map<K,V>
    if yaml_type.startswith("map<") and yaml_type.endswith(">"):
        return (f"std::{yaml_type}", "{}")
    # optional<T>
    if yaml_type.startswith("optional<") and yaml_type.endswith(">"):
        inner = yaml_type[9:-1]
        inner_cpp, _ = _resolve_cpp_type(inner)
        return (f"std::optional<{inner_cpp}>", "std::nullopt")
    # User-defined type
    return (yaml_type, "{}")


def _json_schema_for_type(yaml_type: str) -> dict:
    """Return a deterministic JSON Schema fragment for one YAML type."""
    if yaml_type == "string":
        return {"type": "string"}
    if yaml_type == "bool":
        return {"type": "boolean"}
    if yaml_type in {
        "int8_t", "int16_t", "int32_t", "int64_t",
        "uint8_t", "uint16_t", "uint32_t", "uint64_t",
    }:
        return {"type": "integer"}
    if yaml_type in {"float", "double"}:
        return {"type": "number"}
    if yaml_type.startswith("vector<") and yaml_type.endswith(">"):
        return {
            "type": "array",
            "items": _json_schema_for_type(yaml_type[7:-1]),
        }
    if yaml_type.startswith("optional<") and yaml_type.endswith(">"):
        return {
            "anyOf": [
                _json_schema_for_type(yaml_type[9:-1]),
                {"type": "null"},
            ]
        }
    if yaml_type.startswith("map<") and yaml_type.endswith(">"):
        inner = yaml_type[4:-1]
        _, value_type = inner.split(",", 1)
        return {
            "type": "object",
            "additionalProperties": _json_schema_for_type(value_type.strip()),
        }
    # External C++ JSON types need an explicit schema provider to describe
    # their fields. The generated schema remains valid and marks the reference.
    return {"$ref": yaml_type}


def _json_schema_for_message(namespace: str, message: dict) -> str:
    properties = {
        field["name"]: _json_schema_for_type(field["type"])
        for field in message["fields"]
    }
    required = [
        field["name"] for field in message["fields"]
        if not field["type"].startswith("optional<")
    ]
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"urn:ibmw:{namespace}.{message['name']}",
        "title": f"{namespace}.{message['name']}",
        "type": "object",
        "properties": properties,
        "required": required,
        "additionalProperties": False,
    }
    return json.dumps(schema, sort_keys=True, separators=(",", ":"))


def needs_json_custom_types_header(project: dict) -> bool:
    """Return True when generated code includes the default JSON types header."""
    if project.get("json_types"):
        return True
    return any(
        mod.get("transport") == "json"
        and not mod.get("ros2_import_json_types_header")
        for mod in project.get("modules", [])
    )


def has_generated_json_types(project: dict) -> bool:
    """Return True when the project owns JSON types that can be exported."""
    return bool((project.get("json_types") or {}).get("messages"))


def generate_json_type_support_package(project: dict) -> str:
    """Generate a loadable TypeSupport + SchemaSupport package entrypoint."""
    namespace = project["project"]["_namespace_cpp"]
    messages = (project.get("json_types") or {}).get("messages", [])
    if not messages:
        raise ValueError("cannot generate a JSON TypeSupport package without messages")

    type_support_entries = "\n".join(
        f"    ibmw::json::GetJsonMessageTypeSupport<{namespace}::{message['name']}>(),"
        for message in messages
    )
    schema_support_entries = "\n".join(
        f"    ibmw::json::GetJsonMessageSchemaSupport<{namespace}::{message['name']}>(),"
        for message in messages
    )

    return f"""// This file was generated by ibmw-gen. Do not edit.

#include "type_support/type_support_pkg_main.h"

#include "cpp/util/json_type_support.h"
#include "json_custom_types.h"

namespace {{

const ibmw_type_support_base_t* type_support_array[]{{
{type_support_entries}
}};

const ibmw_schema_support_base_t* schema_support_array[]{{
{schema_support_entries}
}};

const ibmw_schema_support_package_v1_t schema_support_package{{
    .abi_version = IBMW_SCHEMA_SUPPORT_ABI_VERSION_V1,
    .struct_size = sizeof(ibmw_schema_support_package_v1_t),
    .entry_count = sizeof(schema_support_array) / sizeof(schema_support_array[0]),
    .entries = schema_support_array,
    .reserved = {{}}}};

const ibmw_type_support_package_v1_t type_support_package{{
    .abi_version = IBMW_TYPE_SUPPORT_PACKAGE_ABI_VERSION_V1,
    .struct_size = sizeof(ibmw_type_support_package_v1_t),
    .entry_count = sizeof(type_support_array) / sizeof(type_support_array[0]),
    .entries = type_support_array,
    .schema_support = &schema_support_package,
    .reserved = {{}}}};

}}  // namespace

extern "C" {{

const ibmw_type_support_package_v1_t* IbmwDynlibGetTypeSupportPackageV1() {{
  return &type_support_package;
}}

}}  // extern "C"
"""


def generate_json_types(project: dict) -> str:
    """Generate the JSON types header content.

    JSON module typesupport includes ``json_custom_types.h`` unless an imported
    JSON types header is configured.  Projects that only use external C++ JSON
    message types may therefore need a deterministic placeholder header even
    without a top-level ``json_types`` section.
    """
    ns = project["project"]["_namespace_cpp"]
    jt = project.get("json_types") or {}
    messages = jt.get("messages", [])

    # Determine includes
    needs_optional = any(
        f["type"].startswith("optional<")
        for msg in messages for f in msg["fields"]
    )
    needs_vector = any(
        f["type"].startswith("vector<")
        for msg in messages for f in msg["fields"]
    )
    needs_map = any(
        f["type"].startswith("map<")
        for msg in messages for f in msg["fields"]
    )

    lines = []
    lines.append("// This file was generated by ibmw-gen. Do not edit.")
    lines.append("// To add custom types, create a separate header and include it manually.")
    lines.append("")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("#include <string>")
    if needs_vector:
        lines.append("#include <vector>")
    if needs_map:
        lines.append("#include <map>")
    if needs_optional:
        lines.append("#include <optional>")
    lines.append("")
    lines.append("#include <nlohmann/json.hpp>")
    lines.append("")
    lines.append(f"namespace {ns} {{")
    lines.append("")

    for msg in messages:
        lines.append(f"struct {msg['name']} {{")
        lines.append(f'  static constexpr const char* kTypeName = "{ns}.{msg["name"]}";')
        schema = _json_schema_for_message(ns, msg)
        lines.append(
            f'  static constexpr const char* kJsonSchema = R"IBMW_JSON({schema})IBMW_JSON";'
        )
        lines.append("")

        field_names = []
        for f in msg["fields"]:
            cpp_type, default_val = _resolve_cpp_type(f["type"])
            # Use user-specified default if provided
            if "default" in f:
                default_val = str(f["default"])
            field_names.append(f["name"])
            lines.append(f"  {cpp_type} {f['name']}{{{default_val}}};")

        lines.append("")
        field_list = ", ".join(field_names)
        lines.append(f"  NLOHMANN_DEFINE_TYPE_INTRUSIVE_WITH_DEFAULT(")
        lines.append(f"      {msg['name']}, {field_list})")
        lines.append("};")
        lines.append("")

    lines.append(f"}}  // namespace {ns}")
    lines.append("")

    return "\n".join(lines)

# JSON types header generator for ibmw-gen.

"""Generate src/json_custom_types.h for generated JSON modules."""

from textwrap import dedent

# Mapping from YAML type names to C++ type info
_CPP_TYPE_MAP = {
    "string": ("std::string", '""'),
    "bool": ("bool", "false"),
    "int8_t": ("int8_t", "0"),
    "int16_t": ("int16_t", "0"),
    "int32_t": ("int32_t", "0"),
    "int64_t": ("int64_t", "0"),
    "uint8_t": ("uint8_t", "0"),
    "uint16_t": ("uint16_t", "0"),
    "uint32_t": ("uint32_t", "0"),
    "uint64_t": ("uint64_t", "0"),
    "float": ("float", "0.0f"),
    "double": ("double", "0.0"),
}


def _resolve_cpp_type(yaml_type: str) -> tuple[str, str]:
    """Return (cpp_type, default_value) for a YAML type."""
    if yaml_type in _CPP_TYPE_MAP:
        return _CPP_TYPE_MAP[yaml_type]
    # vector<T>
    if yaml_type.startswith("vector<") and yaml_type.endswith(">"):
        inner = yaml_type[7:-1]
        inner_cpp, _ = _resolve_cpp_type(inner)
        return (f"std::vector<{inner_cpp}>", "{}")
    # map<K,V>
    if yaml_type.startswith("map<") and yaml_type.endswith(">"):
        return (f"std::{yaml_type}", "{}")
    # optional<T>
    if yaml_type.startswith("optional<") and yaml_type.endswith(">"):
        inner = yaml_type[9:-1]
        inner_cpp, _ = _resolve_cpp_type(inner)
        return (f"std::optional<{inner_cpp}>", "std::nullopt")
    # User-defined type
    return (yaml_type, "{}")


def needs_json_custom_types_header(project: dict) -> bool:
    """Return True when generated code includes the default JSON types header."""
    if project.get("json_types"):
        return True
    return any(
        mod.get("transport") == "json"
        and not mod.get("ros2_import_json_types_header")
        for mod in project.get("modules", [])
    )


def generate_json_types(project: dict) -> str:
    """Generate the JSON types header content.

    JSON module typesupport includes ``json_custom_types.h`` unless an imported
    JSON types header is configured.  Projects that only use external C++ JSON
    message types may therefore need a deterministic placeholder header even
    without a top-level ``json_types`` section.
    """
    ns = project["project"]["_namespace_cpp"]
    jt = project.get("json_types") or {}
    messages = jt.get("messages", [])

    # Determine includes
    needs_optional = any(
        f["type"].startswith("optional<")
        for msg in messages for f in msg["fields"]
    )
    needs_vector = any(
        f["type"].startswith("vector<")
        for msg in messages for f in msg["fields"]
    )
    needs_map = any(
        f["type"].startswith("map<")
        for msg in messages for f in msg["fields"]
    )

    lines = []
    lines.append("// This file was generated by ibmw-gen. Do not edit.")
    lines.append("// To add custom types, create a separate header and include it manually.")
    lines.append("")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("#include <string>")
    if needs_vector:
        lines.append("#include <vector>")
    if needs_map:
        lines.append("#include <map>")
    if needs_optional:
        lines.append("#include <optional>")
    lines.append("")
    lines.append("#include <nlohmann/json.hpp>")
    lines.append("")
    lines.append(f"namespace {ns} {{")
    lines.append("")

    for msg in messages:
        lines.append(f"struct {msg['name']} {{")
        lines.append(f'  static constexpr const char* kTypeName = "{ns}.{msg["name"]}";')
        lines.append("")

        field_names = []
        for f in msg["fields"]:
            cpp_type, default_val = _resolve_cpp_type(f["type"])
            # Use user-specified default if provided
            if "default" in f:
                default_val = str(f["default"])
            field_names.append(f["name"])
            lines.append(f"  {cpp_type} {f['name']}{{{default_val}}};")

        lines.append("")
        field_list = ", ".join(field_names)
        lines.append(f"  NLOHMANN_DEFINE_TYPE_INTRUSIVE_WITH_DEFAULT(")
        lines.append(f"      {msg['name']}, {field_list})")
        lines.append("};")
        lines.append("")

    lines.append(f"}}  // namespace {ns}")
    lines.append("")

    return "\n".join(lines)

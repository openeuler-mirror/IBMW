# DDS RPC service YAML generator for ibmw-gen.

"""Generate schema/*Service.yaml files from dds_types.rpc_services."""


def generate_dds_rpc_yamls(project: dict) -> list[tuple[str, str]]:
    """Generate RPC service YAML files for dds_idl_gen_rpc.

    Returns list of (rel_path, content) tuples.
    """
    dds = project["dds_types"]
    ns_dotted = dds["namespace"]
    services = dds.get("rpc_services", [])

    results = []

    for svc in services:
        # Skip services with external RPC gencode targets
        if svc.get("_external"):
            continue

        group_name = svc["group"]
        lines = []
        lines.append("# This file was generated by ibmw-gen. Do not edit.")
        lines.append(f"idl_file: {group_name}.idl")
        lines.append(f"module: {ns_dotted}")
        lines.append("")
        lines.append("services:")
        lines.append(f"  - name: {svc['name']}")
        ros2_sn = svc.get("ros2_service_name")
        if ros2_sn:
            lines.append(f"    ros2_service_name: \"{ros2_sn}\"")
        lines.append(f"    methods:")
        for m in svc["methods"]:
            lines.append(f"      - name: {m['name']}")
            lines.append(f"        request: {m['request']}")
            lines.append(f"        response: {m['response']}")
            if m.get("req_dds_type_name"):
                lines.append(f"        req_dds_type_name: \"{m['req_dds_type_name']}\"")
            if m.get("rsp_dds_type_name"):
                lines.append(f"        rsp_dds_type_name: \"{m['rsp_dds_type_name']}\"")
        lines.append("")

        results.append((f"schema/{svc['name']}.yaml", "\n".join(lines)))

    return results

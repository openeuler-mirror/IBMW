# DDS IDL file generator for ibmw-gen.
# Converts YAML dds_types definitions into .idl files.

"""Generate schema/*.idl files from dds_types section."""

# YAML type → IDL type mapping
_IDL_TYPE_MAP = {
    "bool": "boolean",
    "int8": "octet",        # IDL limitation: no signed byte
    "int16": "short",
    "int32": "long",
    "int64": "long long",
    "uint8": "octet",
    "uint16": "unsigned short",
    "uint32": "unsigned long",
    "uint64": "unsigned long long",
    "float": "float",
    "double": "double",
    "string": "string",
    "bytes": "sequence<octet>",
}


def _resolve_idl_type(yaml_type: str, namespace_cpp: str,
                      local_types: set, imported_types: dict) -> str:
    """Convert a YAML field type to an IDL type string."""
    if yaml_type in _IDL_TYPE_MAP:
        return _IDL_TYPE_MAP[yaml_type]
    # vector<T>
    if yaml_type.startswith("vector<") and yaml_type.endswith(">"):
        inner = yaml_type[7:-1]
        inner_idl = _resolve_idl_type(inner, namespace_cpp, local_types, imported_types)
        return f"sequence<{inner_idl}>"
    # Type in current group (no namespace needed)
    if yaml_type in local_types:
        return yaml_type
    # Type from imported group — use fully qualified name
    if yaml_type in imported_types:
        return f"{namespace_cpp}::{yaml_type}"
    # Unknown type — assume it's a user type in current namespace
    return yaml_type


def generate_dds_idl_files(project: dict) -> list[tuple[str, str]]:
    """Generate IDL files. Returns list of (rel_path, content) tuples."""
    dds = project["dds_types"]
    ns_cpp = dds["_namespace_cpp"]
    modules = dds["_modules"]  # e.g. ["ibmw", "protocols", "example"]
    groups = dds.get("groups", [])
    enums = dds.get("enums", [])
    yaml_file = project.get("_yaml_basename", "project.ibmw.yaml")

    # Build a lookup: group_name -> set of message names in that group
    group_msg_names = {}
    for g in groups:
        names = set()
        for msg in g.get("messages", []):
            names.add(msg["name"])
        group_msg_names[g["name"]] = names

    # Build enum lookup: group_name -> list of enums
    enum_by_group = {}
    for e in enums:
        gn = e["group"]
        enum_by_group.setdefault(gn, []).append(e)

    results = []

    for g in groups:
        # Skip groups with external IDL gencode targets — no IDL generation needed
        if g.get("_external"):
            continue

        group_name = g["name"]
        imports = g.get("imports", [])

        # Collect all imported type names
        imported_types = {}
        for imp in imports:
            for name in group_msg_names.get(imp, set()):
                imported_types[name] = imp

        # Local type names in this group
        local_types = group_msg_names[group_name]

        lines = []
        lines.append(f"// This file was generated by ibmw-gen.")
        lines.append(f"// Do not edit — re-run ibmw-gen to regenerate.")
        lines.append("")

        # #include for imports
        for imp in imports:
            lines.append(f'#include "{imp}.idl"')
        if imports:
            lines.append("")

        # Open modules
        for i, m in enumerate(modules):
            indent = "  " * i
            lines.append(f"{indent}module {m} {{")

        inner_indent = "  " * len(modules)

        # Enums for this group
        for e in enum_by_group.get(group_name, []):
            lines.append("")
            lines.append(f"{inner_indent}enum {e['name']} {{")
            vals = []
            for v in e["values"]:
                vals.append(f"{inner_indent}  {v}")
            lines.append(",\n".join(vals))
            lines.append(f"{inner_indent}}};")

        # Structs
        for msg in g.get("messages", []):
            lines.append("")
            lines.append(f"{inner_indent}struct {msg['name']} {{")
            for f in msg["fields"]:
                idl_type = _resolve_idl_type(
                    f["type"], ns_cpp, local_types, imported_types)
                lines.append(f"{inner_indent}  {idl_type} {f['name']};")
            lines.append(f"{inner_indent}}};")

        # Close modules
        for i in range(len(modules) - 1, -1, -1):
            indent = "  " * i
            lines.append(f"{indent}}};")

        lines.append("")

        results.append((f"schema/{group_name}.idl", "\n".join(lines)))

    return results

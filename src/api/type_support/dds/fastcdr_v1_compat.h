// ========================================================================
// CdrVersion — v2 enum, mapped to v1 CdrType
// ========================================================================

struct CdrVersion {
  static constexpr int XCDRv1 = 1;
  static constexpr int XCDRv2 = 2;

  int version;
  constexpr CdrVersion(int v) : version(v) {}

  constexpr bool operator==(const CdrVersion& o) const { return version == o.version; }
  constexpr bool operator!=(const CdrVersion& o) const { return version != o.version; }
};

// ========================================================================
// EncodingAlgorithmFlag — v2 enum, not meaningful in v1
// ========================================================================

enum class EncodingAlgorithmFlag : uint8_t {
  PLAIN_CDR = 0,
  PLAIN_CDR2 = 1,
  DELIMIT_CDR2 = 2,
  PL_CDR2 = 3
};

// ========================================================================
// MemberId — v2 type for XCDR2 member tagging, ignored in v1
// ========================================================================

struct MemberId {
  uint32_t id;
  constexpr explicit MemberId(uint32_t i) : id(i) {}
};

// Make MemberId a no-op when streamed to Cdr in v1: just ignore it.
// The actual data serialization follows via subsequent << operator.
inline Cdr& operator<<(Cdr& cdr, const MemberId& /*mid*/) {
  return cdr;
}

// ========================================================================
// Forward declaration of calculate_serialized_size free function template.
// Specializations are generated by fastddsgen in CdrAux.ipp files.
// Must appear before CdrSizeCalculator which calls it for nested types.
// ========================================================================

class CdrSizeCalculator;

template <typename T>
size_t calculate_serialized_size(
    CdrSizeCalculator& calculator,
    const T& data,
    size_t& current_alignment);

// ========================================================================
// CdrSizeCalculator — v2 class for precise size calculation.
// In v1 we provide a rough estimator that sums up field sizes.
// ========================================================================

class CdrSizeCalculator {
 public:
  explicit CdrSizeCalculator(CdrVersion version)
      : version_(version), current_size_(0) {}

  CdrVersion get_cdr_version() const { return version_; }
  EncodingAlgorithmFlag get_encoding() const { return encoding_; }

  // Type-level begin/end — return 0 overhead for PLAIN_CDR
  size_t begin_calculate_type_serialized_size(
      EncodingAlgorithmFlag encoding,
      size_t& current_alignment) {
    encoding_ = encoding;
    (void)current_alignment;
    return 0;
  }

  size_t end_calculate_type_serialized_size(
      EncodingAlgorithmFlag /*previous_encoding*/,
      size_t& /*current_alignment*/) {
    return 0;
  }

  // ---- Generic calculate_serialized_size (dispatches to template below) ----
  template <typename T>
  size_t calculate_serialized_size(const T& data, size_t& current_alignment) {
    return calculate_serialized_size_impl(data, current_alignment);
  }

  // ---- Per-member size calculation (MemberId is ignored) ----
  template <typename T>
  size_t calculate_member_serialized_size(
      MemberId /*mid*/, const T& data, size_t& current_alignment) {
    return calculate_serialized_size_impl(data, current_alignment);
  }

 private:
  CdrVersion version_;
  EncodingAlgorithmFlag encoding_ = EncodingAlgorithmFlag::PLAIN_CDR;
  size_t current_size_;

  // ---- Primitive type size estimators ----

  // Helper: align up to N bytes
  static size_t align(size_t offset, size_t alignment) {
    return (offset + alignment - 1) & ~(alignment - 1);
  }

  template <typename T>
  typename std::enable_if<std::is_arithmetic<T>::value, size_t>::type
  calculate_serialized_size_impl(const T& /*data*/, size_t& current_alignment) {
    size_t padding = align(current_alignment, sizeof(T)) - current_alignment;
    current_alignment += padding + sizeof(T);
    return padding + sizeof(T);
  }

  // std::string: 4-byte length prefix + characters + 1 null terminator
  size_t calculate_serialized_size_impl(const std::string& data,
                                         size_t& current_alignment) {
    size_t padding = align(current_alignment, 4) - current_alignment;
    size_t str_size = 4 + data.size() + 1;
    current_alignment += padding + str_size;
    return padding + str_size;
  }

  // std::vector: 4-byte length + elements
  template <typename T>
  size_t calculate_serialized_size_impl(const std::vector<T>& data,
                                         size_t& current_alignment) {
    size_t padding = align(current_alignment, 4) - current_alignment;
    size_t total = padding + 4;  // length prefix
    current_alignment += padding + 4;
    for (const auto& elem : data) {
      total += calculate_serialized_size_impl(elem, current_alignment);
    }
    return total;
  }

  // std::array: elements laid out sequentially
  template <typename T, size_t N>
  size_t calculate_serialized_size_impl(const std::array<T, N>& data,
                                         size_t& current_alignment) {
    size_t total = 0;
    for (size_t i = 0; i < N; ++i) {
      total += calculate_serialized_size_impl(data[i], current_alignment);
    }
    return total;
  }

  // Enum types: serialize as their underlying type
  template <typename T>
  typename std::enable_if<std::is_enum<T>::value, size_t>::type
  calculate_serialized_size_impl(const T& data, size_t& current_alignment) {
    using UT = typename std::underlying_type<T>::type;
    UT val = static_cast<UT>(data);
    return calculate_serialized_size_impl(val, current_alignment);
  }

  // Fallback for user-defined types that have a free-function
  // calculate_serialized_size(CdrSizeCalculator&, const T&, size_t&).
  // This enables recursive calculation for nested IDL types.
  template <typename T>
  typename std::enable_if<!std::is_arithmetic<T>::value &&
                          !std::is_enum<T>::value &&
                          !std::is_same<T, std::string>::value,
                          size_t>::type
  calculate_serialized_size_impl(const T& data, size_t& current_alignment) {
    // Call the free function specialization generated by fastddsgen
    return ::eprosima::fastcdr::calculate_serialized_size(*this, data, current_alignment);
  }
};


// FastCDR v2-to-v1 compatibility shim.
//
// fastddsgen v4.x generates CdrAux.ipp files that use FastCDR v2.x APIs
// (CdrSizeCalculator, CdrVersion, MemberId, EncodingAlgorithmFlag, etc.).
// However, ROS Humble ships FastCDR v1.0.x, which lacks these types.
//
// This header provides minimal v2 API definitions that delegate to v1,
// allowing fastddsgen-generated code to compile against FastCDR v1.
//
// IMPORTANT: This file replaces <fastcdr/CdrSizeCalculator.hpp> in the
// include path. It must be included INSTEAD OF the real v2 header.


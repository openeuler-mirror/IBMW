#!/usr/bin/env python3
"""Embed one IDL and its local #include dependencies in a C++ header."""

from __future__ import annotations

import argparse
import pathlib
import re


_INCLUDE_RE = re.compile(r'^\s*#include\s+"([^"]+)"\s*$')


def _resolve_include(
    include_name: str,
    current_dir: pathlib.Path,
    include_dirs: list[pathlib.Path],
) -> pathlib.Path:
    for directory in [current_dir, *include_dirs]:
        candidate = (directory / include_name).resolve()
        if candidate.is_file():
            return candidate
    raise FileNotFoundError(f"cannot resolve IDL include {include_name!r}")


def expand_idl(root: pathlib.Path, include_dirs: list[pathlib.Path]) -> str:
    """Recursively replace quoted IDL includes and emit each file once."""
    emitted: set[pathlib.Path] = set()
    active: set[pathlib.Path] = set()

    def expand(path: pathlib.Path) -> str:
        path = path.resolve()
        if path in active:
            raise ValueError(f"cyclic IDL include involving {path}")
        if path in emitted:
            return f"// IBMW Schema: dependency {path.name} already expanded\n"

        active.add(path)
        emitted.add(path)
        output = [f"// ===== BEGIN IDL: {path.name} =====\n"]
        for line in path.read_text(encoding="utf-8").splitlines(keepends=True):
            match = _INCLUDE_RE.match(line.rstrip("\r\n"))
            if match:
                dependency = _resolve_include(
                    match.group(1), path.parent, include_dirs
                )
                output.append(expand(dependency))
            else:
                output.append(line)
        if output and not output[-1].endswith("\n"):
            output.append("\n")
        output.append(f"// ===== END IDL: {path.name} =====\n")
        active.remove(path)
        return "".join(output)

    return expand(root)


def write_header(output: pathlib.Path, symbol: str, schema_data: str) -> None:
    delimiter = "IBMW_IDL"
    while f'){delimiter}"' in schema_data:
        delimiter += "_"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        "// Auto-generated by embed_idl_schema.py. DO NOT EDIT.\n"
        "#pragma once\n\n"
        "namespace ibmw::dds::schema {\n"
        f'inline constexpr char {symbol}[] = R"{delimiter}('
        f"{schema_data}){delimiter}\";\n"
        "}  // namespace ibmw::dds::schema\n",
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, type=pathlib.Path)
    parser.add_argument("--output", required=True, type=pathlib.Path)
    parser.add_argument("--symbol", required=True)
    parser.add_argument(
        "--include-dir", action="append", default=[], type=pathlib.Path
    )
    args = parser.parse_args()

    schema_data = expand_idl(
        args.input, [directory.resolve() for directory in args.include_dir]
    )
    write_header(args.output, args.symbol, schema_data)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
